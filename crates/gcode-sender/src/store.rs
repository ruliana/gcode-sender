//! Jobs on disk. Everything the server needs to know about a job lives
//! here, so a restarted server picks up where the last one stopped.
//!
//! Layout: `<data>/jobs/<id>/program.gcode` holds the upload as received and
//! `<data>/jobs/<id>/job.json` holds the record. Records are replaced with an
//! atomic rename, so a crash never leaves a half-written record behind.

use std::io::Write;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::bounds::Bounds;
use crate::program::{self, ProgramLine};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum JobState {
    /// Uploaded and ready to start.
    Loaded,
    Running,
    Paused,
    /// A stop was requested and the controller is being brought to rest.
    Stopping,
    Completed,
    Stopped,
    Failed,
    /// The server went down while the job was active.
    Interrupted,
}

impl JobState {
    pub fn is_active(self) -> bool {
        matches!(self, Self::Running | Self::Paused | Self::Stopping)
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct LineError {
    /// Line number in the uploaded file.
    pub line: usize,
    pub code: u32,
    #[serde(default)]
    pub message: String,
    pub text: String,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct JobRecord {
    pub id: String,
    pub name: String,
    pub state: JobState,
    /// Lines that will be streamed, after comments and blank lines are removed.
    pub total_lines: usize,
    /// Lines the controller has acknowledged with `ok` or `error`.
    pub acked_lines: usize,
    /// File line number of the last acknowledged line.
    pub last_acked_line: Option<usize>,
    pub created_at_ms: u64,
    pub started_at_ms: Option<u64>,
    pub finished_at_ms: Option<u64>,
    /// File line number the last resume restarted from, if the job was
    /// resumed after an interruption.
    #[serde(default)]
    pub resumed_from_line: Option<usize>,
    /// The G54 work offset (machine coordinates) the job last ran with, so
    /// a resume can tell that the work zero has moved since.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub work_offset: Option<[f64; 3]>,
    /// Why the job paused, failed or was interrupted.
    pub reason: Option<String>,
    pub line_errors: Vec<LineError>,
}

pub fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

pub struct JobStore {
    data_dir: PathBuf,
    root: PathBuf,
}

impl JobStore {
    pub fn open(data_dir: &Path) -> Result<Self> {
        let root = data_dir.join("jobs");
        std::fs::create_dir_all(&root).with_context(|| format!("creating {}", root.display()))?;
        Ok(Self {
            data_dir: data_dir.to_path_buf(),
            root,
        })
    }

    fn dir(&self, id: &str) -> Option<PathBuf> {
        // Ids are generated by us; refuse anything that could escape the root.
        Uuid::parse_str(id).ok()?;
        Some(self.root.join(id))
    }

    /// The machine boundaries, if any have been set.
    pub fn bounds(&self) -> Result<Option<Bounds>> {
        match std::fs::read(self.data_dir.join("bounds.json")) {
            Ok(bytes) => Ok(Some(serde_json::from_slice(&bytes)?)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e.into()),
        }
    }

    pub fn set_bounds(&self, bounds: Option<&Bounds>) -> Result<()> {
        let path = self.data_dir.join("bounds.json");
        match bounds {
            Some(b) => write_atomic(&path, &serde_json::to_vec_pretty(b)?),
            None => match std::fs::remove_file(&path) {
                Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e.into()),
                _ => Ok(()),
            },
        }
    }

    pub fn create(&self, name: Option<String>, source: &str) -> Result<JobRecord> {
        let id = Uuid::new_v4().to_string();
        let dir = self.root.join(&id);
        std::fs::create_dir_all(&dir)?;
        write_atomic(&dir.join("program.gcode"), source.as_bytes())?;
        let record = JobRecord {
            name: name.unwrap_or_else(|| id.clone()),
            id,
            state: JobState::Loaded,
            total_lines: program::prepare(source).len(),
            acked_lines: 0,
            last_acked_line: None,
            created_at_ms: now_ms(),
            started_at_ms: None,
            finished_at_ms: None,
            resumed_from_line: None,
            work_offset: None,
            reason: None,
            line_errors: Vec::new(),
        };
        self.save(&record)?;
        Ok(record)
    }

    pub fn save(&self, record: &JobRecord) -> Result<()> {
        let dir = self.dir(&record.id).context("invalid job id")?;
        let json = serde_json::to_vec_pretty(record)?;
        write_atomic(&dir.join("job.json"), &json)
    }

    pub fn get(&self, id: &str) -> Result<Option<JobRecord>> {
        let Some(dir) = self.dir(id) else {
            return Ok(None);
        };
        match std::fs::read(dir.join("job.json")) {
            Ok(bytes) => Ok(Some(serde_json::from_slice(&bytes)?)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e.into()),
        }
    }

    pub fn program(&self, id: &str) -> Result<Vec<ProgramLine>> {
        let dir = self.dir(id).context("invalid job id")?;
        let source = std::fs::read_to_string(dir.join("program.gcode"))?;
        Ok(program::prepare(&source))
    }

    pub fn list(&self) -> Result<Vec<JobRecord>> {
        let mut jobs = Vec::new();
        for entry in std::fs::read_dir(&self.root)? {
            let name = entry?.file_name();
            if let Some(job) = self.get(&name.to_string_lossy())? {
                jobs.push(job);
            }
        }
        jobs.sort_by_key(|j| j.created_at_ms);
        Ok(jobs)
    }

    pub fn delete(&self, id: &str) -> Result<bool> {
        let Some(dir) = self.dir(id) else {
            return Ok(false);
        };
        match std::fs::remove_dir_all(dir) {
            Ok(()) => Ok(true),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(false),
            Err(e) => Err(e.into()),
        }
    }

    /// Marks jobs that were active when the last server stopped. The
    /// controller may have kept running buffered moves after we went away,
    /// so the job cannot simply continue.
    pub fn recover(&self) -> Result<Vec<JobRecord>> {
        let mut recovered = Vec::new();
        for mut job in self.list()? {
            if job.state.is_active() {
                job.state = JobState::Interrupted;
                job.reason = Some("the server stopped while the job was active".into());
                job.finished_at_ms = Some(now_ms());
                self.save(&job)?;
                recovered.push(job);
            }
        }
        Ok(recovered)
    }
}

fn write_atomic(path: &Path, bytes: &[u8]) -> Result<()> {
    let tmp = path.with_extension("tmp");
    let mut file = std::fs::File::create(&tmp)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    std::fs::rename(&tmp, path)?;
    Ok(())
}
